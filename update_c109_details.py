import subprocess
import json

details_markdown = """## 1. 企画概要
C109頒布予定で篠澤広×数学の合同企画「篠澤広と数学しよう！」の第4弾をやります。

---

## 2. レギュレーション
- 「篠澤広」と「数学」に関する作品であればSSだろうと漫画だろうと構いません。
- 登場キャラクターについても、「学園アイドルマスターの二次創作」の範囲内に収まれば「篠澤広」以外のキャラクターが登場しても構いません。
- 「数学」の範囲ですが、「数学の応用」の範囲であれば物理学や経済学など、数学以外の学問分野でも大丈夫です。(e.g. Black-Scholes方程式と金融工学)
- なお、どの形式、どの分野で制作するかにかかわらず、学力レベル以外では当該アイドルのイメージから大幅に逸脱しないようお願いします。
- 口調・呼称等が異なるなどの場合は大幅に改稿することになりますので、校閲校正の前にある程度確認しておいてください。場合によっては掲載をお断りする可能性もございますことをご承知おきください。

---

## 3. 提出形式
- **SSの場合**: 原則として `tex` での提出をお願いします。ひな形となるtexファイルはDiscordサーバにて配布します。
- **漫画の場合**: `B5` サイズの `pdf` での提出をお願いします。解像度その他の情報につきましては主宰までご相談ください。
- ※ texの環境がないからwordで提出したい等、これら以外の形式での提出を希望される方は、主宰にご相談ください。

---

## 4. スケジュール
- **2026/09/06**: 参加表明締切
- **2026/10/18**: 初稿締切，以降校閲校正期間
- **2026/11/29**: 最終稿締切，組版最終チェック
- **2026/12/29**: C109 頒布日
"""

issues = [
    {"num": 277, "header": "### 📌 本ステップ: 参加表明締切 (2026/09/06)\n\n"},
    {"num": 278, "header": "### 📌 本ステップ: 初稿締切・校閲校正期間開始 (2026/10/18)\n\n"},
    {"num": 279, "header": "### 📌 本ステップ: 最終稿締切・組版最終チェック (2026/11/29)\n\n"},
    {"num": 280, "header": "### 📌 本ステップ: C109 頒布日 (2026/12/29)\n\n"}
]

for item in issues:
    body = item["header"] + details_markdown
    res = subprocess.run([
        "gh", "issue", "edit", str(item["num"]),
        "--repo", "ozetudo/calendar",
        "--body", body
    ], capture_output=True, text=True)
    if res.returncode == 0:
        print(f"Updated Issue #{item['num']} with full details.")
    else:
        print(f"Error updating #{item['num']}: {res.stderr}")

print("Done!")
